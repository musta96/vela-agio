export const findCatalogEntry = (symbol: string): CatalogEntry | undefined =>
  STOCK_CATALOG.find((s) => s.symbol === symbol);

export const searchCatalog = (query: string, limit = 60): CatalogEntry[] => {
  if (!query.trim()) return [];
  const q = query.toLowerCase().trim();
  return STOCK_CATALOG.filter(
    (s) =>
      s.symbol.toLowerCase().includes(q) ||
      s.name.toLowerCase().includes(q) ||
      s.market.toLowerCase().includes(q)
  ).slice(0, limit);
};