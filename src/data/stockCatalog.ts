// Currency symbol helper
export const currencySign = (code?: string) => {
  switch ((code || "").toUpperCase()) {
    case "USD": return "$";
    case "EUR": return "€";
    case "GBP": return "£";
    case "GBp": return "p";
    case "CHF": return "CHF ";
    case "SEK": return "kr ";
    case "NOK": return "kr ";
    case "DKK": return "kr ";
    default: return code ? `${code} ` : "";
  }
};

