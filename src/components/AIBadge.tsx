import { Sparkles } from "lucide-react";
import { cn } from "@/lib/utils";
import {
  Tooltip,
  TooltipContent,
  TooltipTrigger,
} from "@/components/ui/tooltip";

interface AIBadgeProps {
  className?: string;
  model?: string;
  label?: string;
}

/**
 * Required transparency label for AI-generated content (EU AI Act Art. 50).
 * Use anywhere an LLM produced the visible text.
 */
export function AIBadge({ className, model, label = "AI-generated" }: AIBadgeProps) {
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span
          className={cn(
            "inline-flex items-center gap-1 rounded-full border border-primary/30 bg-primary/10 px-2 py-0.5 text-[10px] font-medium text-primary",
            className,
          )}
        >
          <Sparkles className="h-2.5 w-2.5" />
          {label}
        </span>
      </TooltipTrigger>
      <TooltipContent side="top" className="max-w-xs text-xs">
        Generated by an AI model{model ? ` (${model})` : ""}. May be inaccurate or incomplete —
        verify before acting on it. Not investment advice.
      </TooltipContent>
    </Tooltip>
  );
}